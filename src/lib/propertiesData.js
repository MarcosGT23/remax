import { fetchAPI } from "./api.js";

export function safeFormatPrice(val) {
  if (val === null || val === undefined || val === '') return '1,200';
  if (typeof val === 'number') {
    return isNaN(val) ? '1,200' : val.toLocaleString('en-US');
  }
  const str = String(val).trim();
  if (str.toLowerCase().includes('nan')) return '1,200';
  if (str.includes(',')) {
    const cleaned = str.replace(/[^0-9,.]/g, '');
    return cleaned || '1,200';
  }
  const num = parseFloat(str.replace(/[^0-9.]/g, ''));
  return isNaN(num) ? str : num.toLocaleString('en-US');
}

export function safeMediaUrl(mediaObj, fallback = '/images/commercial-roofing.webp') {
  if (!mediaObj) return fallback;
  let rawUrl = '';

  // Strapi v5: media object directly has a `url` field at root level
  if (typeof mediaObj === 'string') {
    rawUrl = mediaObj;
  } else if (mediaObj?.url) {
    rawUrl = mediaObj.url;
  } else if (mediaObj?.data?.attributes?.url) {
    // Strapi v4 format
    rawUrl = mediaObj.data.attributes.url;
  } else if (mediaObj?.data?.url) {
    rawUrl = mediaObj.data.url;
  } else if (mediaObj?.attributes?.url) {
    rawUrl = mediaObj.attributes.url;
  }

  if (!rawUrl) return fallback;
  if (rawUrl.startsWith('http://') || rawUrl.startsWith('https://')) return rawUrl;
  const strapiUrl = (typeof import.meta !== 'undefined' && import.meta.env?.STRAPI_URL) || 'http://localhost:1337';
  return `${strapiUrl}${rawUrl.startsWith('/') ? '' : '/'}${rawUrl}`;
}

export function safeGalleryUrls(galleryField, coverFallback) {
  if (!galleryField) return [coverFallback];

  let items = [];
  // Strapi v5: gallery is directly an array of media objects with `url` at root
  if (Array.isArray(galleryField)) {
    items = galleryField;
  } else if (Array.isArray(galleryField?.data)) {
    // Strapi v4 format
    items = galleryField.data;
  }

  const urls = items
    .map(item => safeMediaUrl(item, null))
    .filter(Boolean);

  if (urls.length === 0) return [coverFallback];
  return urls;
}

export function resolvePropertyCoords(item = {}) {
  const rawLat = parseFloat(item.latitude || item.lat);
  const rawLng = parseFloat(item.longitude || item.lng);

  if (!isNaN(rawLat) && !isNaN(rawLng) && rawLat !== 0 && rawLng !== 0) {
    return { lat: rawLat, lng: rawLng };
  }

  const text = `${item.address || ''} ${item.title || ''} ${item.zone || ''} ${item.city || ''}`.toLowerCase();

  // Specific Zones & Neighborhoods in Bolivia
  if (text.includes("villa 1ro de mayo") || text.includes("villa primero de mayo") || text.includes("1ro de mayo")) {
    return { lat: -17.7942, lng: -63.1415 };
  }
  if (text.includes("plan 3000")) {
    return { lat: -17.8250, lng: -63.1360 };
  }
  if (text.includes("equipetrol")) {
    return { lat: -17.7684, lng: -63.1952 };
  }
  if (text.includes("urubó") || text.includes("urubo")) {
    return { lat: -17.7550, lng: -63.2200 };
  }
  if (text.includes("sirari")) {
    return { lat: -17.7610, lng: -63.1870 };
  }
  if (text.includes("hilandería") || text.includes("hilanderia")) {
    return { lat: -17.7910, lng: -63.2080 };
  }
  if (text.includes("banzer")) {
    return { lat: -17.7350, lng: -63.1700 };
  }
  if (text.includes("calacoto")) {
    return { lat: -16.5395, lng: -68.0872 };
  }
  if (text.includes("achumani")) {
    return { lat: -16.5290, lng: -68.0750 };
  }
  if (text.includes("sopocachi")) {
    return { lat: -16.5110, lng: -68.1280 };
  }
  if (text.includes("prado")) {
    return { lat: -17.3855, lng: -66.1578 };
  }
  if (text.includes("sarco")) {
    return { lat: -17.3730, lng: -66.1720 };
  }

  // City Level Fallbacks
  if (text.includes("la paz")) {
    return { lat: -16.5000, lng: -68.1500 };
  }
  if (text.includes("cochabamba")) {
    return { lat: -17.3895, lng: -66.1568 };
  }
  if (text.includes("tarija")) {
    return { lat: -21.5355, lng: -64.7296 };
  }

  // Default: Santa Cruz de la Sierra Center
  return { lat: -17.7833, lng: -63.1821 };
}

export function getPropertyById(id) {
  const p = propertiesData.find(p => p.id === id || p.shortId === id || p.slug === id) || propertiesData[0];
  const coords = resolvePropertyCoords(p);
  return { ...p, lat: coords.lat, lng: coords.lng };
}

